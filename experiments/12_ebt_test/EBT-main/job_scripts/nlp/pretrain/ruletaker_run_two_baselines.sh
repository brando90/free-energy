#!/usr/bin/env bash
set -euo pipefail

: "${WANDB_API_KEY:?Set WANDB_API_KEY before running}"

mkdir -p logs/ruletaker

TRANSFORMER_GPU="${TRANSFORMER_GPU:-0}"
EBT_GPU="${EBT_GPU:-0}"
RULETAKER_MAX_ITEMS="${RULETAKER_MAX_ITEMS:-2048}"
MAX_STEPS="${MAX_STEPS:-50000}"
TRANSFORMER_BATCH_SIZE="${TRANSFORMER_BATCH_SIZE:-${BATCH_SIZE:-16}}"
EBT_BATCH_SIZE="${EBT_BATCH_SIZE:-${BATCH_SIZE:-16}}"
TRANSFORMER_ACCUMULATE_GRAD_BATCHES="${TRANSFORMER_ACCUMULATE_GRAD_BATCHES:-${ACCUMULATE_GRAD_BATCHES:-1}}"
EBT_ACCUMULATE_GRAD_BATCHES="${EBT_ACCUMULATE_GRAD_BATCHES:-${ACCUMULATE_GRAD_BATCHES:-1}}"
TRANSFORMER_TRAIN_METRIC_LOG_BATCH_SIZE="${TRANSFORMER_TRAIN_METRIC_LOG_BATCH_SIZE:-${TRAIN_METRIC_LOG_BATCH_SIZE:-0}}"
EBT_TRAIN_METRIC_LOG_BATCH_SIZE="${EBT_TRAIN_METRIC_LOG_BATCH_SIZE:-${TRAIN_METRIC_LOG_BATCH_SIZE:-0}}"
TRANSFORMER_AGGREGATE_TRAIN_METRICS_OVER_ACCUMULATION="${TRANSFORMER_AGGREGATE_TRAIN_METRICS_OVER_ACCUMULATION:-${AGGREGATE_TRAIN_METRICS_OVER_ACCUMULATION:-0}}"
EBT_AGGREGATE_TRAIN_METRICS_OVER_ACCUMULATION="${EBT_AGGREGATE_TRAIN_METRICS_OVER_ACCUMULATION:-${AGGREGATE_TRAIN_METRICS_OVER_ACCUMULATION:-0}}"
RULETAKER_TRAIN_AR_INTERVAL="${RULETAKER_TRAIN_AR_INTERVAL:-500}"
VAL_CHECK_INTERVAL="${VAL_CHECK_INTERVAL:-200}"
LIMIT_VAL_BATCHES="${LIMIT_VAL_BATCHES:-256}"
VALIDATE_BEFORE_TRAINING="${VALIDATE_BEFORE_TRAINING:-0}"

CUDA_VISIBLE_DEVICES="${TRANSFORMER_GPU}" \
RULETAKER_MAX_ITEMS="${RULETAKER_MAX_ITEMS}" \
MAX_STEPS="${MAX_STEPS}" \
BATCH_SIZE="${TRANSFORMER_BATCH_SIZE}" \
ACCUMULATE_GRAD_BATCHES="${TRANSFORMER_ACCUMULATE_GRAD_BATCHES}" \
TRAIN_METRIC_LOG_BATCH_SIZE="${TRANSFORMER_TRAIN_METRIC_LOG_BATCH_SIZE}" \
AGGREGATE_TRAIN_METRICS_OVER_ACCUMULATION="${TRANSFORMER_AGGREGATE_TRAIN_METRICS_OVER_ACCUMULATION}" \
RULETAKER_TRAIN_AR_INTERVAL="${RULETAKER_TRAIN_AR_INTERVAL}" \
VAL_CHECK_INTERVAL="${VAL_CHECK_INTERVAL}" \
LIMIT_VAL_BATCHES="${LIMIT_VAL_BATCHES}" \
VALIDATE_BEFORE_TRAINING="${VALIDATE_BEFORE_TRAINING}" \
RUN_NAME="${TRANSFORMER_RUN_NAME:-ruletaker_transformer_2xs_tied_smoke}" \
bash job_scripts/nlp/pretrain/ruletaker_transformer_baseline.sh \
  > logs/ruletaker/transformer.log 2>&1 &
transformer_pid=$!

CUDA_VISIBLE_DEVICES="${EBT_GPU}" \
RULETAKER_MAX_ITEMS="${RULETAKER_MAX_ITEMS}" \
MAX_STEPS="${MAX_STEPS}" \
BATCH_SIZE="${EBT_BATCH_SIZE}" \
ACCUMULATE_GRAD_BATCHES="${EBT_ACCUMULATE_GRAD_BATCHES}" \
TRAIN_METRIC_LOG_BATCH_SIZE="${EBT_TRAIN_METRIC_LOG_BATCH_SIZE}" \
AGGREGATE_TRAIN_METRICS_OVER_ACCUMULATION="${EBT_AGGREGATE_TRAIN_METRICS_OVER_ACCUMULATION}" \
RULETAKER_TRAIN_AR_INTERVAL="${RULETAKER_TRAIN_AR_INTERVAL}" \
VAL_CHECK_INTERVAL="${VAL_CHECK_INTERVAL}" \
LIMIT_VAL_BATCHES="${LIMIT_VAL_BATCHES}" \
VALIDATE_BEFORE_TRAINING="${VALIDATE_BEFORE_TRAINING}" \
RUN_NAME="${EBT_RUN_NAME:-ruletaker_ebt_2xs_mcmc4_smoke}" \
bash job_scripts/nlp/pretrain/ruletaker_ebt_baseline.sh \
  > logs/ruletaker/ebt.log 2>&1 &
ebt_pid=$!

echo "Transformer PID: ${transformer_pid}"
echo "EBT PID: ${ebt_pid}"
wait "${transformer_pid}" "${ebt_pid}"
